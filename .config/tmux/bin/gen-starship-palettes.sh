#!/usr/bin/env bash
#
# Generate Starship palettes from the tmux theme files.
#
# Each tmux theme names its colors differently (catppuccin uses "mauve",
# rose-pine uses "iris", equinox uses "plum"), so palettes are derived from the
# *resolved* tmux options rather than the variable names: a throwaway tmux
# server sources each theme, then we read the hex values back out. Roles come
# from options every theme sets, which is what makes this work across all of
# them.
#
# Output is written between marker comments in starship.toml. Hand edits to a
# generated palette are overwritten, so tune the tmux theme instead and re-run.

set -euo pipefail

readonly TMUX_DIR="${TMUX_DIR:-$HOME/.config/tmux}"
readonly THEME_DIR="${THEME_DIR:-$TMUX_DIR/config}"
readonly REGISTRY="${REGISTRY:-$TMUX_DIR/themes.registry}"
readonly STARSHIP_TOML="${STARSHIP_TOML:-$HOME/.config/starship.toml}"
readonly SOCKET="starship-palette-gen-$$"
readonly BEGIN_MARK="# >>> generated by gen-starship-palettes.sh >>>"
readonly END_MARK="# <<< generated by gen-starship-palettes.sh <<<"

cleanup() { tmux -L "$SOCKET" kill-server 2>/dev/null || true; }
trap cleanup EXIT

die() { printf 'error: %s\n' "$*" >&2; exit 1; }

# Read one field (fg= or bg=) out of a tmux style string.
style_field() {
    printf '%s' "$1" | tr ',' '\n' | grep "^$2=" | head -1 | cut -d= -f2
}

# First hex color appearing anywhere in a string.
first_hex() {
    printf '%s' "$1" | grep -o '#[0-9a-fA-F]\{6\}' | head -1
}

# Fall back through a list of candidates, returning the first non-empty one.
coalesce() {
    local v
    for v in "$@"; do
        [[ -n "$v" ]] && { printf '%s' "$v"; return; }
    done
}

# Some themes leave the online-status icons uncolored. Recover a green by
# looking for a conventionally-named green variable in the theme source.
green_from_source() {
    grep -iE '^(green|success|pine|moss|seafoam|aqua|foam|teal|lime)="#' "$1" \
        | head -1 | cut -d'"' -f2
}

emit_palette() {
    local name="$1" file="$2"

    tmux -L "$SOCKET" source-file "$file" 2>/dev/null \
        || die "theme failed to parse: $file"

    local status_style message_style border_style mode_st
    status_style=$(tmux -L "$SOCKET" show-options -gv status-style)
    message_style=$(tmux -L "$SOCKET" show-options -gv message-style)
    border_style=$(tmux -L "$SOCKET" show-options -gv pane-active-border-style)
    mode_st=$(tmux -L "$SOCKET" show-options -gv mode-style)

    local match_style mark_style bell_style activity_style online offline panes
    match_style=$(tmux -L "$SOCKET" show-options -gv copy-mode-match-style)
    mark_style=$(tmux -L "$SOCKET" show-options -gv copy-mode-mark-style)
    bell_style=$(tmux -L "$SOCKET" show-options -gwv window-status-bell-style)
    activity_style=$(tmux -L "$SOCKET" show-options -gwv window-status-activity-style)
    online=$(tmux -L "$SOCKET" show-options -gv @online_icon 2>/dev/null || true)
    offline=$(tmux -L "$SOCKET" show-options -gv @offline_icon 2>/dev/null || true)
    panes=$(tmux -L "$SOCKET" show-options -gv display-panes-active-colour)

    # Roles. color_text sits on vivid accent backgrounds; color_text_end sits
    # on the muted UI segments at the end of the prompt.
    local accent text_on_accent text_on_ui ui1 ui2 green red yellow purple pink
    accent=$(style_field "$border_style" fg)
    text_on_accent=$(style_field "$message_style" fg)
    text_on_ui=$(style_field "$status_style" fg)
    ui1=$(style_field "$mode_st" bg)
    ui2=$(style_field "$status_style" bg)
    green=$(coalesce "$(first_hex "$online")" "$(green_from_source "$file")" "$panes")
    red=$(coalesce "$(first_hex "$offline")" "$(style_field "$bell_style" fg)")
    yellow=$(coalesce "$(style_field "$match_style" bg)" "$(style_field "$activity_style" fg)")
    pink=$(coalesce "$(style_field "$mark_style" bg)" "$red")
    purple=$(coalesce "$panes" "$accent")

    for role in accent text_on_accent text_on_ui ui1 ui2 green red yellow pink purple; do
        [[ -n "${!role}" ]] || die "$name: could not resolve '$role'"
    done

    cat <<PALETTE
[palettes.$name]
color_text = "$text_on_accent"
color_text_end = "$text_on_ui"
color_start = "$accent"
color_dir = "$green"
color_git = "$yellow"
color_lang = "$purple"
color_ui1 = "$ui1"
color_ui2 = "$ui2"
color_green = "$green"
color_red = "$red"
color_yellow = "$yellow"
color_purple = "$pink"

PALETTE
}

main() {
    [[ -d "$THEME_DIR" ]] || die "theme dir not found: $THEME_DIR"
    [[ -f "$REGISTRY" ]] || die "registry not found: $REGISTRY"
    [[ -f "$STARSHIP_TOML" ]] || die "starship config not found: $STARSHIP_TOML"
    command -v tmux >/dev/null || die "tmux not found"

    tmux -L "$SOCKET" -f /dev/null new-session -d "sleep 120" 2>/dev/null \
        || die "could not start scratch tmux server"

    local generated
    generated=$(mktemp)
    {
        printf '%s\n' "$BEGIN_MARK"
        printf '# Derived from the tmux themes. Run bin/gen-starship-palettes.sh to refresh.\n\n'
        local name file _mode _desc count=0
        while IFS='|' read -r name file _mode _desc; do
            [[ -z "$name" || "$name" == \#* ]] && continue
            [[ -f "$THEME_DIR/$file" ]] || { printf 'skip %s: missing %s\n' "$name" "$file" >&2; continue; }
            emit_palette "$name" "$THEME_DIR/$file"
            count=$((count + 1))
        done < "$REGISTRY"
        printf '%s\n' "$END_MARK"
        printf '%d palettes\n' "$count" >&2
    } > "$generated"

    # Splice into starship.toml, replacing any previous generated block.
    local out
    out=$(mktemp)
    if grep -qF "$BEGIN_MARK" "$STARSHIP_TOML"; then
        awk -v b="$BEGIN_MARK" -v e="$END_MARK" -v g="$generated" '
            index($0, b) == 1 { while ((getline line < g) > 0) print line; skip = 1; next }
            index($0, e) == 1 { skip = 0; next }
            !skip { print }
        ' "$STARSHIP_TOML" > "$out"
    else
        cat "$STARSHIP_TOML" "$generated" > "$out"
    fi

    cat "$out" > "$STARSHIP_TOML"   # write through the symlink rather than replacing it
    rm -f "$out" "$generated"
    printf 'wrote palettes to %s\n' "$STARSHIP_TOML"
}

main "$@"
